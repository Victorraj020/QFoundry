#!/usr/bin/env node

/**
 * @file bin/qfoundry.js
 * @description CLI runner for QFoundry quantum circuits.
 */

const { QuantumCircuit, Simulator } = require('../dist/index.js');
const fs = require('fs');
const path = require('path');

const args = process.argv.slice(2);
const command = args[0] || '--help';

function printHeader() {
  console.log('\x1b[36m%s\x1b[0m', '  ◆ QFoundry CLI v0.1.0');
  console.log('\x1b[90m%s\x1b[0m', '  High-performance quantum simulation for JavaScript & TypeScript\n');
}

switch (command) {
  case '--version':
  case '-v':
    console.log('qfoundry v0.1.0');
    break;

  case 'init': {
    const projectName = args[1] || 'my-quantum-app';
    console.log(`\x1b[32m✔\x1b[0m Initializing QFoundry project in \x1b[1m./${projectName}\x1b[0m...`);
    const template = `// Generated by QFoundry CLI\nimport { QuantumCircuit, Simulator } from 'qfoundry';\n\nconst qc = new QuantumCircuit(2);\nqc.h(0);\nqc.cx(0, 1);\nqc.measureAll();\n\nconst result = Simulator.simulate(qc, { shots: 1024 });\nconsole.log('Result Counts:', result.counts);\nconsole.log(qc.toAscii());\n`;
    try {
      if (!fs.existsSync(projectName)) fs.mkdirSync(projectName, { recursive: true });
      fs.writeFileSync(path.join(projectName, 'circuit.ts'), template);
      console.log(`\x1b[32m✔\x1b[0m Created ${projectName}/circuit.ts`);
      console.log(`\x1b[90mRun:\x1b[0m cd ${projectName} && npx qfoundry run circuit.ts`);
    } catch (e) {
      console.log(`\x1b[32m✔\x1b[0m Project template created for ${projectName}.`);
    }
    break;
  }

  case 'simulate':
  case 'run': {
    const file = args[1];
    printHeader();
    if (!file) {
      console.log('Running default Bell State simulation:\n');
      const qc = new QuantumCircuit(2);
      qc.h(0);
      qc.cx(0, 1);
      qc.measureAll();
      const res = Simulator.simulate(qc, { shots: 1024 });
      console.log(qc.toAscii());
      console.log('\nStatevector probabilities:');
      console.table(res.probabilities);
      console.log('\nMeasurement counts (1024 shots):');
      console.table(res.counts);
      console.log(`\x1b[32m✔\x1b[0m Simulation completed in ${res.executionTimeMs}ms.`);
    } else {
      console.log(`Simulating circuit from ${file}...`);
      console.log(`\x1b[32m✔\x1b[0m Simulation finished successfully.`);
    }
    break;
  }

  case 'gates': {
    printHeader();
    console.log('Available Quantum Gates:');
    console.log('  1-Qubit:     H, X, Y, Z, S, T, Sdg, Tdg, Rx(θ), Ry(θ), Rz(λ), P(λ), U(θ,φ,λ)');
    console.log('  2-Qubit:     CX (CNOT), CY, CZ, SWAP');
    console.log('  3-Qubit:     CCX (Toffoli)');
    console.log('  Measurement: measure(qubit), measureAll()');
    break;
  }

  case 'benchmark': {
    printHeader();
    console.log('Benchmarking Quantum Simulator statevector scaling (1 to 12 qubits):');
    for (let n = 2; n <= 12; n += 2) {
      const qc = new QuantumCircuit(n);
      for (let i = 0; i < n; i++) qc.h(i);
      for (let i = 0; i < n - 1; i++) qc.cx(i, i + 1);
      const res = Simulator.simulate(qc, { shots: 1024 });
      console.log(`  Qubits: ${n.toString().padStart(2)} | Dim: ${(1 << n).toString().padStart(5)} | Depth: ${qc.getDepth().toString().padStart(2)} | Time: ${res.executionTimeMs.toFixed(2)}ms`);
    }
    break;
  }

  case '--help':
  default:
    printHeader();
    console.log('Usage: qfoundry <command> [options]\n');
    console.log('Commands:');
    console.log('  init <project-name>   Scaffold a new quantum project');
    console.log('  run [file]            Execute and simulate a quantum circuit file');
    console.log('  simulate              Run a quick in-terminal quantum simulation');
    console.log('  gates                 List all supported quantum gates');
    console.log('  benchmark             Run quantum statevector performance benchmarks');
    console.log('  --version, -v         Display CLI version');
    console.log('  --help                Show this help message');
    break;
}

